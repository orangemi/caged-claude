"""Host side of the host bridge (docs/host-bridge.md): SSH over a Unix socket.

Runs with the host's python3 and only the standard library, outside the
launcher container: ./cage calls it after `up` (start) and `down` (stop)
with a plan file that the launcher wrote. For every connection on
state/<instance>/bridge/host.sock it runs a project-owned `sshd -i` as the
calling user, so no network port is opened and the firewall is untouched.

  python3 bridge.py start PLAN   prepare keys and config, then daemonize
  python3 bridge.py stop PLAN    stop the listener and remove the socket

On macOS no Unix socket crosses into Docker's VM, so the plan's transport
is "tcp": the listener binds 127.0.0.1:PORT instead, which containers reach
as host.docker.internal:PORT (docs/host-bridge.md §6).
"""
import json
import os
from pathlib import Path
import shutil
import signal
import socket
import subprocess
import sys
import time

HOST_ALIAS = 'caged-host'


class BridgeError(Exception):
    pass


class Plan:
    def __init__(self, data):
        self.instance = data['instance']
        self.user = data['user']
        self.sshd_hint = data.get('sshd')
        self.transport = data.get('transport', 'unix')
        self.port = int(data.get('port') or 0)
        if self.transport not in ('unix', 'tcp') or (self.transport == 'tcp' and not 1024 <= self.port <= 65535):
            raise BridgeError('Plan transport must be unix, or tcp with a port from 1024 to 65535')
        self.bridge = Path(data['bridge'])     # state/<instance>/bridge, read-only in the container
        self.config = Path(data['config'])     # state/<instance>/bridge-host, host only
        for path in (self.bridge, self.config):
            if not path.is_absolute():
                raise BridgeError('Plan paths must be absolute')

    socket = property(lambda self: self.bridge / 'host.sock')

    def endpoint(self):
        return f'127.0.0.1:{self.port}' if self.transport == 'tcp' else str(self.socket)
    pidfile = property(lambda self: self.bridge / 'listener.pid')
    client_key = property(lambda self: self.bridge / 'client_ed25519')
    known_hosts = property(lambda self: self.bridge / 'known_hosts')
    host_key = property(lambda self: self.config / 'ssh_host_ed25519_key')
    authorized_keys = property(lambda self: self.config / 'authorized_keys')
    sshd_config = property(lambda self: self.config / 'sshd_config')
    sshd_log = property(lambda self: self.config / 'sshd.log')
    listener_log = property(lambda self: self.config / 'listener.log')


def load(path):
    try:
        return Plan(json.loads(Path(path).read_text()))
    except (OSError, ValueError, KeyError) as error:
        raise BridgeError(f'Unreadable bridge plan {path}: {error}') from None


def find_sshd(hint):
    for candidate in ([hint] if hint else []) + [shutil.which('sshd'), '/usr/sbin/sshd', '/usr/local/sbin/sshd']:
        if candidate and os.access(candidate, os.X_OK):
            return candidate
    raise BridgeError('sshd not found; install openssh-server (the system SSH service need not run) '
                      'or set host_bridge.enabled: false')


def keygen(path, comment):
    if path.exists():
        return
    tool = shutil.which('ssh-keygen')
    if not tool:
        raise BridgeError('ssh-keygen not found; install OpenSSH')
    subprocess.run([tool, '-q', '-t', 'ed25519', '-N', '', '-C', comment, '-f', str(path)],
                   check=True, stdin=subprocess.DEVNULL, capture_output=True)
    os.chmod(path, 0o600)


def write(path, text, mode=0o600):
    temporary = path.with_name(path.name + '.tmp')
    descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    with os.fdopen(descriptor, 'w') as handle:
        handle.write(text)
    os.chmod(temporary, mode)
    os.rename(temporary, path)


def sshd_config(plan):
    return f'''# Generated by ./cage for the host bridge of {plan.instance}; do not edit.
# Runs as {plan.user} via `sshd -i` per connection on {plan.endpoint()}.
HostKey {plan.host_key}
AuthorizedKeysFile {plan.authorized_keys}
AllowUsers {plan.user}
PubkeyAuthentication yes
PasswordAuthentication no
KbdInteractiveAuthentication no
UsePAM no
PermitRootLogin no
PermitTTY yes
AllowTcpForwarding yes
AllowAgentForwarding no
X11Forwarding no
PermitUserEnvironment no
Subsystem sftp internal-sftp
LogLevel VERBOSE
PidFile none
'''


def prepare(plan):
    """Create keys and configuration; return the sshd binary."""
    sshd = find_sshd(plan.sshd_hint)
    plan.config.mkdir(parents=True, exist_ok=True, mode=0o700)
    os.chmod(plan.config, 0o700)
    plan.bridge.mkdir(parents=True, exist_ok=True, mode=0o700)
    os.chmod(plan.bridge, 0o700)
    keygen(plan.host_key, f'{HOST_ALIAS}:{plan.instance}')
    keygen(plan.client_key, f'caged-claude:{plan.instance}')
    client = (plan.client_key.with_name(plan.client_key.name + '.pub')).read_text().strip()
    # restrict disables everything; re-enable only what the bridge offers.
    write(plan.authorized_keys, f'restrict,pty,port-forwarding {client}\n')
    host = plan.host_key.with_name(plan.host_key.name + '.pub').read_text().split()
    write(plan.known_hosts, f'{HOST_ALIAS} {host[0]} {host[1]}\n', 0o644)
    write(plan.sshd_config, sshd_config(plan))
    result = subprocess.run([sshd, '-t', '-f', str(plan.sshd_config)], capture_output=True, text=True)
    if result.returncode:
        raise BridgeError('sshd rejected the bridge configuration: ' + (result.stderr or result.stdout).strip())
    return sshd


def running_pid(plan):
    try:
        pid = int(plan.pidfile.read_text())
    except (OSError, ValueError):
        return None
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return None
    except PermissionError:
        return None  # not ours
    command = subprocess.run(['ps', '-p', str(pid), '-o', 'command='], capture_output=True, text=True).stdout
    return pid if 'bridge.py' in command else None


def stop(plan):
    pid = running_pid(plan)
    if pid:
        os.kill(pid, signal.SIGTERM)
        for _ in range(50):
            if running_pid(plan) is None:
                break
            time.sleep(0.1)
    for path in (plan.socket, plan.pidfile):
        try:
            path.unlink()
        except FileNotFoundError:
            pass


def serve(plan, sshd, ready=lambda: None):
    """Accept connections forever; each becomes the stdio of one `sshd -i`."""
    signal.signal(signal.SIGCHLD, signal.SIG_IGN)  # sessions are reaped automatically
    try:
        plan.socket.unlink()
    except FileNotFoundError:
        pass
    os.umask(0o077)
    if plan.transport == 'tcp':
        # Loopback only: nothing on the LAN can reach it; containers come in
        # through Docker's host.docker.internal forwarding.
        server = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        server.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        try:
            server.bind(('127.0.0.1', plan.port))
        except OSError as error:
            raise BridgeError(f'Cannot listen on 127.0.0.1:{plan.port}: {error.strerror}; '
                              'set host_bridge.port to a free port') from None
    else:
        server = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        server.bind(str(plan.socket))
        os.chmod(plan.socket, 0o600)
    server.listen(16)

    def shutdown(_signum, _frame):
        server.close()
        for path in (plan.socket, plan.pidfile):
            try:
                path.unlink()
            except FileNotFoundError:
                pass
        os._exit(0)

    signal.signal(signal.SIGTERM, shutdown)
    signal.signal(signal.SIGINT, shutdown)
    write(plan.pidfile, f'{os.getpid()}\n', 0o644)
    ready()
    while True:
        connection, _ = server.accept()
        try:
            subprocess.Popen([sshd, '-i', '-f', str(plan.sshd_config), '-E', str(plan.sshd_log)],
                             stdin=connection.fileno(), stdout=connection.fileno(),
                             stderr=subprocess.DEVNULL, close_fds=True, start_new_session=True)
        except OSError as error:
            print(f'{time.strftime("%Y-%m-%dT%H:%M:%S")} cannot start sshd: {error}', flush=True)
        finally:
            connection.close()


def start(plan):
    if os.geteuid() == 0:
        raise BridgeError('Refusing to run the host bridge as root')
    stop(plan)  # a listener from an earlier session (or a stale socket) is replaced
    sshd = prepare(plan)
    ready_read, ready_write = os.pipe()
    if os.fork():
        os.close(ready_write)
        signal_ready = os.read(ready_read, 1)
        if signal_ready != b'1':
            raise BridgeError(f'Host bridge listener did not start; see {plan.listener_log}')
        return
    # Daemon: detach from the terminal and from ./cage.
    os.close(ready_read)
    os.setsid()
    if os.fork():
        os._exit(0)
    log = os.open(plan.listener_log, os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600)
    null = os.open(os.devnull, os.O_RDONLY)
    os.dup2(null, 0)
    os.dup2(log, 1)
    os.dup2(log, 2)
    os.chdir('/')
    def ready():
        os.write(ready_write, b'1')
        os.close(ready_write)

    try:
        serve(plan, sshd, ready)
    except Exception as error:  # reaches the log; the parent sees no readiness byte
        print(f'{time.strftime("%Y-%m-%dT%H:%M:%S")} listener failed: {error}', flush=True)
        os._exit(1)


def main(argv):
    if len(argv) != 2 or argv[0] not in ('start', 'stop'):
        print(__doc__, file=sys.stderr)
        return 2
    try:
        plan = load(argv[1])
        if argv[0] == 'start':
            start(plan)
            print(f'  ✓ Host bridge  ssh host (from ./cage shell) reaches {plan.user} on this machine ({plan.endpoint()})')
        else:
            stop(plan)
        return 0
    except (BridgeError, OSError, subprocess.CalledProcessError) as error:
        print(f'Host bridge unavailable: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
